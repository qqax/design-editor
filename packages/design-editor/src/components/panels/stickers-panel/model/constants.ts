export const STICKERS: StickerDef[] = Object.entries(STICKER_FILES).flatMap(
  ([category, files]) =>
    files.map((file) => ({
      id: file.replace(/\.(svg|png)$/i, '').replace(/_/g, '-'),

      label: file
        .replace(/\.(svg|png)$/i, '')
        .replace(/_/g, ' ')
        .replace(/\b\w/g, (l) => l.toUpperCase()),

      category: category as StickerCategoryType,

      file,
    }))
);

